#!/usr/bin/env python3
"""
Emit the set of guest functions XenonRecomp could not translate.

Why this exists
---------------
The crash handler maps a host PC to the guest function containing it by taking
the nearest function start at or below it. XenonRecomp emits some functions as a
single `.long 0x0` - four bytes of data that is not valid PowerPC - and those
stubs sit adjacent to the real functions in host address order.

A PC inside a real function that follows a stub is therefore attributed to the
stub, and the reported offset is measured from four bytes of padding. That number
means nothing, and it is worse than useless because it looks like a measurement.

Observed, before this existed:

    guest addr  : 0x823460D4  (sub_823460D4, +1081 bytes)

`sub_823460D4` is a stub. The real `sub_823460D8` is aliased twelve bytes after
it, and the registers at that fault (lr = 0x823460E0, r12 = 0x82346E34) are
inside the real function's prologue and its call site. The "+1081" was an
artefact of the attribution, not a location.

Why it is generated at build time
---------------------------------
This was first attempted as a runtime scan of the generated sources. It found
the files and read them, and still found zero stubs, while the identical
algorithm run offline finds 9,660. That discrepancy was never resolved.

Doing it here removes the whole class of problem: no runtime file I/O, no path
resolution, no dependence on where the exe was copied, and no chance of the
answer differing between the build that produced the binary and the run that
crashes in it. If the recompiler output changes, this runs again and the answer
changes with it.

Usage:
    gen_stub_symbols.py <ppc-dir> <output-header>
"""

import os
import re
import sys

HEADER = """// Generated by tools/gen_stub_symbols.py - do not edit.
//
// Guest functions XenonRecomp emitted as an unresolved `.long 0x0`. A fault
// attributed to one of these has a meaningless offset, because the symbol marks
// the start of four bytes of padding rather than the start of real code.
#pragma once

static const uint32_t kCod3StubSymbolCount = %d;

static const uint32_t kCod3StubSymbols[] = {
%s};
"""


def find_stubs(ppc_dir):
    """Return the guest addresses whose generated body is a single .long 0x0."""
    stubs = []
    func_re = re.compile(r'^PPC_FUNC_IMPL\(__imp__(sub_\w+)\) \{$', re.M)

    for name in sorted(os.listdir(ppc_dir)):
        if not (name.startswith('ppc_recomp.') and name.endswith('.cpp')):
            continue

        path = os.path.join(ppc_dir, name)
        with open(path, encoding='utf-8', errors='replace') as f:
            text = f.read()

        for m in func_re.finditer(text):
            # The body runs to the closing brace at column 0.
            end = text.find('\n}\n', m.end())
            if end < 0:
                continue

            body = text[m.end():end]
            # Strip the prologue line; what remains must be exactly the
            # unresolved data directive and nothing else.
            lines = [l.strip() for l in body.splitlines()
                     if l.strip() and not l.strip().startswith('PPC_FUNC_PROLOGUE')]

            if len(lines) == 1 and lines[0] in ('// .long 0x0', '.long 0x0;'):
                stubs.append(int(m.group(1)[4:], 16))

    return sorted(set(stubs))


def main(argv):
    if len(argv) != 3:
        sys.stderr.write(__doc__)
        return 2

    ppc_dir, out_path = argv[1], argv[2]
    stubs = find_stubs(ppc_dir)

    rows = []
    for i in range(0, len(stubs), 8):
        rows.append('    ' + ' '.join('0x%08X,' % a for a in stubs[i:i + 8]))

    text = HEADER % (len(stubs), '\n'.join(rows) if rows else '    0')

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)

    # Printed because a silent count of zero is indistinguishable from a broken
    # scan, which is exactly how the runtime version failed unnoticed.
    print('gen_stub_symbols: %d unresolved stub(s) -> %s' % (len(stubs), out_path))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
